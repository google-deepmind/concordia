r"""Push audit: what each Steward move does to each world's climate.

A move's push is shown beside it so a player can weigh it.
The same move does very different things on different worlds: bright clouds
cool a warm Daisyworld about 6 °C but a cold, icy world three times as much,
where the ice spreads. So the pushes of the moves that change the climate
are measured on every world: from tick 6 of a few seeded worlds, each move
is made once on a copy of the planet and the next four turns compared with
waiting. The results go to `data/pushes.yaml`, which `game.new_game` reads
(a scenario's own hand-written `pushes:` still win). A colony's recipes are
measured too: what moving the colonists' labor into each does to the stores.
Each move's change to the temperature over six turns is kept as its profile,
for the Steward's forecast.

  python -m examples.deep_time.push_audit            # print
  python -m examples.deep_time.push_audit --write    # data/pushes.yaml
"""

# pylint: disable=g-doc-args,g-doc-return-or-yield,g-long-ternary

from collections.abc import Callable, Mapping, Sequence
import copy
import os
from typing import Any, TypedDict

from absl import app
from absl import flags
from examples.deep_time import game as game_lib
from examples.deep_time.world import data
import numpy as np
import yaml

# Effects measured on each world (others say what they do in their data).
MEASURED_KINDS = frozenset({
    'seed',
    'albedo_pulse',
    'carbon_drawdown',
    'outgassing',
    'veil',
    'reserve',
    'transplant',
})
SEEDS = (0, 1, 2, 3)
START_TICK = 6
TURNS = 4
PROFILE_TURNS = 6  # Turns of each move's profile, for forecasts.
PATH = os.path.join(data.DATA_DIR, 'pushes.yaml')


class Change(TypedDict):
  temp_c: list[float]  # Change in the global temperature, each turn.
  co2: float  # Change in the air's carbon (relative to the start) by then.
  bio: float  # Change in the planet's biodiversity by then.


class Measured(Change):
  profile: list[float]  # The temperature's change each turn, for longer.


HEADER = """\
# Generated by push_audit.py --write: do not edit. What each Steward move
# that changes the climate does on each world, measured at
# tick {start} and halfway through the game, on {seeds} seeded worlds, over
# the next {turns} turns against waiting (a range where the two differ). A
# scenario's own `pushes:` override these. `profiles:` hold each move's mean
# change to the temperature over {profile} turns, for the Steward's forecast.
"""


def measure(
    scenario: str,
    seeds: Sequence[int] = SEEDS,
    start: int = START_TICK,
    turns: int = TURNS,
    profile: int = PROFILE_TURNS,
) -> dict[str, Measured]:
  """Mean change each climate move makes against waiting.

  Args:
    scenario: Scenario key.
    seeds: Worlds to average over.
    start: Tick at which each move is made.
    turns: Turns compared after the move.
    profile: Turns of the temperature's change kept as its profile.

  Returns:
    Intervention key -> {'temp_c': change per turn, 'co2': change in the
    air's carbon (relative to the start) after the last turn, 'bio':
    likewise, 'profile': the temperature's change over `profile` turns}.
  """
  changes: dict[str, list[tuple[np.ndarray, float, float]]] = {}
  length = max(turns, profile)
  for seed in seeds:
    planet = game_lib.new_game(scenario, seed=seed).planet
    for _ in range(start):
      planet.advance()
    snapshot = copy.deepcopy(planet.get_state())

    def play(move=None, planet=planet, snapshot=snapshot):
      planet.set_state(copy.deepcopy(snapshot))
      planet.omega = 1e6  # Affordable, whatever it costs.
      if move is not None:
        planet.apply_intervention('Gaia', move)
      temps, co2, bio = [], 1.0, 0.0
      for turn in range(length):
        planet.advance()
        temps.append(planet.temperature_c())
        if turn + 1 == turns:
          co2 = planet.carbon.relative_co2() if planet.carbon else 1.0
          bio = planet.biodiversity()
      return np.array(temps), co2, bio

    temps, co2, bio = play()
    for move in planet.interventions():
      if move.effect.get('kind') not in MEASURED_KINDS:
        continue
      moved, moved_co2, moved_bio = play(move)
      changes.setdefault(move.key, []).append(
          (moved - temps, moved_co2 - co2, moved_bio - bio)
      )
  out: dict[str, Measured] = {}
  for key, rows in changes.items():
    temps = [round(float(x), 2) for x in np.mean([t for t, _, _ in rows], 0)]
    out[key] = Measured(
        temp_c=temps[:turns],
        co2=round(float(np.mean([c for _, c, _ in rows])), 3),
        bio=round(float(np.mean([b for _, _, b in rows])), 3),
        profile=temps[:profile],
    )
  return out


def _degrees(value: float) -> str:
  value = abs(value)
  if value < 2.5:
    return f'{round(value * 2) / 2:g}'
  return f'{value:.0f}'


def _spread(
    values: Sequence[float], show: Callable[[float], str], floor: float
) -> tuple[str, str]:
  """('', '6'), ('', '6 to 16') or ('up to ', '16') across the moments."""
  lo, hi = min(abs(v) for v in values), max(abs(v) for v in values)
  if hi > 1.6 * lo and show(lo) != show(hi):
    if lo < floor:
      return 'up to ', show(hi)
    return '', f'{show(lo)} to {show(hi)}'
  return '', show(sum(abs(v) for v in values) / len(values))


def describe(changes: Sequence[Change], note: str = '') -> str:
  """A push in words: how far and how long it moves the climate.

  Args:
    changes: The move's change measured at one or more moments of a game
      (`measure`); a range is given where they differ much.
    note: What the measurement cannot show, put first (e.g. 'greens bare land').

  Returns:
    The push, e.g. 'cools about 6 °C next turn, fading over a few turns'.
  """
  firsts = [float(c['temp_c'][0]) for c in changes]
  lasts = [float(c['temp_c'][-1]) for c in changes]
  turns = len(changes[0]['temp_c'])
  strongest = max(range(len(changes)), key=lambda i: abs(firsts[i]))
  first, last = firsts[strongest], lasts[strongest]
  if abs(first) >= 0.5:
    verb = 'warms' if first > 0 else 'cools'
    same = [f for f in firsts if f * first > 0]
    if abs(last) >= 0.6 * abs(first):
      how = 'lasting'
    elif abs(last) < 0.35 * abs(first):
      how = 'fading over a few turns'
    else:
      how = 'fading slowly'
    upto, size = _spread(same, _degrees, 0.5)
    climate = f'{verb} {upto or "about "}{size} °C next turn, {how}'
  elif max(abs(v) for v in lasts) >= 0.5:
    last = max(lasts, key=abs)
    verb = 'warms' if last > 0 else 'cools'
    same = [v for v in lasts if v * last > 0]
    upto, size = _spread(same, _degrees, 0.5)
    climate = f'{verb} {upto or "about "}{size} °C over {turns} turns'
  else:
    climate = 'hardly changes the warmth'
  co2s = [float(c['co2']) for c in changes]
  co2 = max(co2s, key=abs)
  carbon = ''
  if abs(co2) >= 0.02:
    same = [v for v in co2s if v * co2 > 0]
    sign = '+' if co2 > 0 else '−'
    upto, size = _spread(same, lambda v: f'{sign}×{abs(v):.2f}', 0.02)
    carbon = f'; {upto}{size} carbon in the air'
  bios = [float(c.get('bio', 0.0)) for c in changes]
  bio = max(bios, key=abs)
  life = ''
  if abs(bio) >= 0.005:
    same = [v for v in bios if v * bio > 0]
    sign = '+' if bio > 0 else '−'
    upto, size = _spread(same, lambda v: f'{sign}{abs(v):.2f}', 0.005)
    life = f'; biodiversity {upto}{size}'
  return (f'{note}; ' if note else '') + climate + carbon + life


def starts(scenario: str) -> tuple[int, ...]:
  """When moves are measured: early in a game, and halfway through it."""
  length = int(data.scenario(scenario)['max_ticks'])
  return tuple(sorted({START_TICK, max(START_TICK, length // 2)}))


def runs(
    scenario: str, seeds: Sequence[int] = SEEDS
) -> list[dict[str, Measured]]:
  """A scenario's climate moves measured at each of its moments."""
  return [measure(scenario, seeds, start) for start in starts(scenario)]


def pushes(
    scenario: str,
    seeds: Sequence[int] = SEEDS,
    found: Sequence[Mapping[str, Measured]] | None = None,
) -> dict[str, str]:
  """Measured pushes of a scenario's climate moves, in words."""
  notes = {
      i['key']: str(i.get('note', ''))
      for i in data.load('interventions.yaml')['interventions']
  }
  found = found if found is not None else runs(scenario, seeds)
  return {
      key: describe([m[key] for m in found], notes.get(key, ''))
      for key in sorted(found[0])
  }


def profiles(found: Sequence[Mapping[str, Measured]]) -> dict[str, list[float]]:
  """Each move's change to the temperature turn by turn, over the moments.

  The Steward's forecast adds these to its late readings:
  a move it made since a reading was taken has acted on the planet the
  reading has not yet shown.
  """
  return {
      key: [
          round(float(x), 1)
          for x in np.mean([m[key]['profile'] for m in found], axis=0)
      ]
      for key in sorted(found[0])
  }


STORES = ('food', 'air', 'water', 'power', 'panels')
COLONY_SEEDS = tuple(range(8))
COLONY_YEAR = 5


def describe_colony(
    stores: Mapping[str, float], warmed: float, years: int
) -> str:
  """A colony recipe's push in words: what more labor there does to stores.

  Args:
    stores: Change in each store a year, against not shifting the labor.
    warmed: Change in the colony's sky temperature over `years`.
    years: Years compared.

  Returns:
    E.g. 'food +2.6 a year; water −3.5, power −1.0, air −0.8 a year; the sky
    −0.6 °C in 4 years': the gains, the three largest costs, the sky.
  """
  gains = sorted(((v, r) for r, v in stores.items() if v >= 0.2), reverse=True)
  losses = sorted((v, r) for r, v in stores.items() if v <= -0.2)[:3]
  sky = (
      f'the sky {"+" if warmed > 0 else "−"}{abs(warmed):.1f} °C in'
      f' {years} years'
      if abs(warmed) >= 0.3
      else ''
  )
  parts = [sky] if sky and warmed > 0 else []
  if gains:
    parts.append(', '.join(f'{r} +{v:.1f}' for v, r in gains) + ' a year')
  if losses:
    parts.append(', '.join(f'{r} −{abs(v):.1f}' for v, r in losses) + ' a year')
  if sky and warmed < 0:
    parts.append(sky)
  return '; '.join(parts) or 'little change to the stores'


def colony_pushes(
    scenario: str,
    seeds: Sequence[int] = COLONY_SEEDS,
    year: int = COLONY_YEAR,
    years: int = TURNS,
) -> dict[str, str]:
  """What more labor in each of a colony's recipes does to its stores.

  The colonists' share (the scenario's `colony.focus_share`) moves to the
  recipe at `year`, on copies of the colony of each seeded world, and the
  stores and sky `years` later are compared with not moving it.

  Args:
    scenario: Scenario key.
    seeds: Worlds to average over.
    year: Year of the shift.
    years: Years compared.

  Returns:
    Recipe key -> push (empty for a scenario without a colony).
  """
  share = float(
      (data.scenario(scenario).get('colony') or {}).get('focus_share', 0.15)
  )
  changes: dict[str, list[tuple[dict[str, float], float]]] = {}
  for seed in seeds:
    planet = game_lib.new_game(scenario, seed=seed).planet
    colony = planet.colony
    if colony is None:
      return {}
    for _ in range(year):
      planet.advance()
    for design in colony.design_labels:  # Every recipe, known or not yet.
      colony.receive_design(design)
    snapshot = copy.deepcopy(colony.get_state())

    def run(recipe=None, colony=colony, snapshot=snapshot):
      colony.set_state(copy.deepcopy(snapshot))
      if recipe is not None:
        colony.shift_labor(recipe, share)
      before, temp = {r: colony.stock(r) for r in STORES}, colony.temp_c
      for _ in range(years):
        colony.step()
      return (
          {r: (colony.stock(r) - before[r]) / years for r in STORES},
          colony.temp_c - temp,
      )

    base, base_temp = run()
    for recipe in colony.recipes:
      moved, moved_temp = run(recipe.key)
      changes.setdefault(recipe.key, []).append(
          ({r: moved[r] - base[r] for r in STORES}, moved_temp - base_temp)
      )
  return {
      key: describe_colony(
          {r: float(np.mean([row[0][r] for row in rows])) for r in STORES},
          float(np.mean([row[1] for row in rows])),
          years,
      )
      for key, rows in sorted(changes.items())
  }


def measured(scenario: str) -> dict[str, Any]:
  """A scenario's entry in pushes.yaml: moves, and its colony's recipes."""
  found = runs(scenario)
  entry: dict[str, Any] = dict(pushes(scenario, found=found))
  if found[0]:
    entry['profiles'] = profiles(found)
  colony = colony_pushes(scenario)
  if colony:
    entry['colony'] = colony
  return entry


class _Dumper(yaml.SafeDumper):
  """Writes lists (the profiles) on one line each."""


_Dumper.add_representer(
    list,
    lambda dumper, value: dumper.represent_sequence(
        'tag:yaml.org,2002:seq', value, flow_style=True
    ),
)


def main(argv: Sequence[str]) -> None:
  del argv
  values = flags.FLAGS
  scenarios = values.scenarios or list(data.load('scenarios.yaml'))
  table = {s: measured(s) for s in scenarios}
  table = {s: p for s, p in table.items() if p}
  if not values.write:
    print(yaml.safe_dump(table, allow_unicode=True, sort_keys=True, width=200))
    return
  merged = dict(data.load('pushes.yaml') or {}) if os.path.exists(PATH) else {}
  merged.update(table)
  with open(PATH, 'w', encoding='utf-8') as f:
    f.write(
        HEADER.format(
            start=START_TICK,
            seeds=len(SEEDS),
            turns=TURNS,
            profile=PROFILE_TURNS,
        )
    )
    yaml.dump(
        merged,
        f,
        Dumper=_Dumper,
        allow_unicode=True,
        sort_keys=True,
        width=200,
    )
  print(f'wrote {PATH}: {sum(len(p) for p in table.values())} pushes')


if __name__ == '__main__':
  flags.DEFINE_list('scenarios', [], 'Scenario keys (default: all).')
  flags.DEFINE_bool('write', False, 'Write data/pushes.yaml.')
  app.run(main)
